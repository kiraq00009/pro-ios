    static let all: [Phrase] = raw.enumerated().map { i, r in Phrase(id: i, cat: r.0, ar: r.1, fa: r.2, say: r.3) }

    static func of(_ cat: String) -> [Phrase] { all.filter { $0.cat == cat } }

    /// بحث يتحمّل اختلاف ي/ی وك/ک والتشكيل
    static func search(_ q: String) -> [Phrase] {
        let n = key(q)
        guard !n.isEmpty else { return [] }
        return all.filter { key($0.ar).contains(n) || key($0.fa).contains(n) || key($0.say).contains(n) }
    }

    static func key(_ s: String) -> String {
        Script.toArabic(Script.toPersian(s)).replacingOccurrences(of: "\u{200C}", with: " ")
            .replacingOccurrences(of: "أ", with: "ا").replacingOccurrences(of: "إ", with: "ا").replacingOccurrences(of: "آ", with: "ا")
            .lowercased()
    }
